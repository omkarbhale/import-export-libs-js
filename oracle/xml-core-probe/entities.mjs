// Writes src/xml/html-entities.ts from the table .NET Framework holds (case "5.entities" of fixtures/xml-core/vectors.json).
// Run from the repository root: `node oracle/xml-core-probe/entities.mjs`.
import { readFileSync, writeFileSync } from "node:fs";

const { vectors } = JSON.parse(readFileSync("fixtures/xml-core/vectors.json", "utf8"));
const list = vectors.find((v) => v.id === "5.entities").expect.list;
const pairs = list.map((entry) => {
  const dash = entry.indexOf("-", 1);
  const character = entry.slice(0, dash);
  const name = entry.slice(dash + 1);
  if (character.length !== 1) throw new Error(`entity ${name} is not a single UTF-16 unit`);
  return `${name}:${character.charCodeAt(0).toString(16).toUpperCase().padStart(4, "0")}`;
});
const lines = [];
for (let i = 0; i < pairs.length; i += 8) lines.push(`  "${pairs.slice(i, i + 8).join(" ")}",`);
writeFileSync(
  "src/xml/html-entities.ts",
  `// Generated by oracle/xml-core-probe/entities.mjs from the table of .NET Framework 4.8's WebUtility (fixtures/xml-core/vectors.json,
// case 5.entities): the ${pairs.length} HTML 4.01 entity names plus \`apos\`, each with its UTF-16 code unit in hexadecimal. Do not edit by hand.

const ENTRIES = [
${lines.join("\n")}
];

/** Entity name to character, as \`WebUtility.HtmlDecode\` knows them. Names are case-sensitive. */
export const HTML_ENTITIES: ReadonlyMap<string, string> = new Map(
  ENTRIES.flatMap((line) => line.split(" ")).map((pair) => {
    const [name = "", code = ""] = pair.split(":");
    return [name, String.fromCharCode(parseInt(code, 16))] as const;
  }),
);
`,
);
console.log(`wrote ${pairs.length} entities`);

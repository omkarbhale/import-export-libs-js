/** The requests the rewrites make that are not lookups: the follow-up fetches of `CExportItems` (EXP-048 to EXP-051). */
export type RewriteRequests = Pick<
  CExportItems,
  "queryAutoGeneratedRelationships" | "fetchRelationshipItemType" | "fetchFieldProperty" | "fetchDrRelationship"
>;

const SOAP = "http://schemas.xmlsoap.org/soap/envelope/";

/** The path to the Result item that `Export` hands to the float-property step: the envelope names are matched by local name. */
const SOAP_RESULT_ITEM =
  `*[local-name()='Envelope' and (namespace-uri()='${SOAP}' or namespace-uri()='')]` +
  `/*[local-name()='Body' and (namespace-uri()='${SOAP}' or namespace-uri()='')]` +
  `/*[local-name()='Result' and (namespace-uri()='${SOAP}' or namespace-uri()='')]/Item`;

/** The Result item of a document, as the steps below find it. */
const RESULT_ITEM = ".//*[local-name(.)='Result']/Item";

const NOT_A_SINGLE_ITEM = "Not a single item";
const NOT_A_SINGLE_ITEM_ARGUMENT = "The argument passed to the method is not a single item";

/** The `System.Exception` IOM throws when an operation that needs one item has none or several. */
const notASingleItem = (): DotNetException => new DotNetException("System.Exception", NOT_A_SINGLE_ITEM);

/** The attribute `name` of an element, or undefined when it has none. */
const attributeValue = (element: XmlElement, name: string): string | undefined => element.getAttributeNode(name)?.value;

/** A node the path selected, as an element. */
const asElement = (node: XmlNode | null): XmlElement | null => node as XmlElement | null;

/**
 * The rewrites `CExportItems.Export` makes to the server's answer between the fetch and `export.xsl` (steps 5 to 12 of EXP-100),
 * each on the answer's DOM, in place. The follow-up fetches go through the `CExportItems` requests and the lookups through the
 * helper's cache; the rewrites of references (steps 9 and 10) are the helper's own (`helper.references`).
 *
 * @spec EXP-100 EXP-101
 */
export class ExportRewrites {
  constructor(
    private readonly helper: CItemHelper,
    private readonly requests: RewriteRequests,
  ) {}

  /**
   * Steps 5 to 12, in order, each only when its condition holds. `versionable` is the answer of `IsVersionable` for the item's
   * type, which the fetch already asked for.
   *
   * @spec EXP-100
   */
  async rewrite(doc: XmlDocument, typeName: string, versionable: boolean): Promise<void> {
    await this.removeSpecialRelationshipsIfNeed(typeName, doc);
    this.processXProperties(doc);
    if (versionable) this.replaceIdWithConfigId(doc);
    if (typeName === "RelationshipType") await this.processRelationshipType(doc);
    else if (typeName === "Sequence") this.processSequence(doc);
    else if (typeName === "Form") await this.processForm(doc);
    await this.helper.references.processIndependentRelatedItems(doc);
    const resultItem = asElement(selectSingleNode(SOAP_RESULT_ITEM, doc));
    if (resultItem) await this.helper.references.processPropertiesOfTypeItem(resultItem);
    if (typeName === "dr_RelationshipFamily") await this.includeDrRelationshipAsValue(doc);
    if (typeName === "ac_PolicyAccessItemAttribute" && this.helper.engine !== "12.0") await this.includeDrRelationshipAsValue(doc);
    if (typeName === "dac_DomainDefinition") this.indentConditionXmlInDAC(doc);
  }

  /**
   * Step 5: the ItemType and xClassificationTree cleanups. Any other type has none.
   *
   * @spec EXP-100 EXP-103 EXP-105
   */
  async removeSpecialRelationshipsIfNeed(typeName: string, doc: XmlDocument): Promise<void> {
    if (typeName === "ItemType") await this.removeAutoGeneratedRelationships(doc);
    else if (typeName === "xClassificationTree") this.removeSystemRelationshipsFromXTree(doc);
  }

  /**
   * An ItemType: the Client Event `cmf_OnShowContainer` is removed from the answer. Then the content types linked to the ItemType
   * are looked up and their generated relationships removed from a copy of the answer, which nobody writes (EXP-104).
   *
   * @spec EXP-048 EXP-103 EXP-104
   */
  async removeAutoGeneratedRelationships(doc: XmlDocument): Promise<void> {
    const clientEvent = selectSingleNode("//Relationships/Item[@type='Client Event' and related_id[@keyed_name='cmf_OnShowContainer']]", doc);
    if (clientEvent?.parentNode) removeChild(clientEvent.parentNode, clientEvent);

    const copy = loadXml(outerXml(doc), { preserveWhitespace: true });
    const itemType = asElement(selectSingleNode("//Item", copy));
    if (!itemType) return;
    const contentTypes = await this.requests.queryAutoGeneratedRelationships(itemIdOf(itemType));
    if (contentTypes.isError || documentOuterXml(contentTypes.document) === "<Empty />") return;
    const [contentType, ...others] = contentTypes.items;
    if (others.length > 0) throw notASingleItem();
    if (!contentType) return;
    for (const elementType of relationshipsOf(contentType)) {
      removeRelationshipHelper(elementType, itemType);
      for (const propertyType of relationshipsOf(elementType)) removeRelationshipHelper(propertyType, itemType);
    }
  }

  /**
   * An xClassificationTree: every `xClass_xProperty_Flatten` relationship of each of its `xClass` relationships is removed.
   *
   * @spec EXP-105
   */
  removeSystemRelationshipsFromXTree(doc: XmlDocument): void {
    const root = selectSingleNode("//Result/Item", doc);
    if (!root) throw notASingleItem();
    for (const xClass of selectNodes("Relationships/Item[@type='xClass']", root)) this.removeRelationshipsByType("xClass_xProperty_Flatten", xClass);
  }

  /**
   * Removes the relationships of an item that have this type.
   *
   * @spec EXP-105
   */
  removeRelationshipsByType(type: string, item: XmlNode): void {
    for (const relationship of selectNodes(`Relationships/Item[@type='${type}']`, item)) {
      if (relationship.parentNode) removeChild(relationship.parentNode, relationship);
    }
  }

  /**
   * Step 6: every extended property (an element called `xp-…` in an `Item`) gets a `set` attribute, first among its attributes,
   * that says which of its parts the import sets; `explicit` and `is_null` are dropped when they are not what that says.
   *
   * @spec EXP-106
   */
  processXProperties(doc: XmlDocument): void {
    for (const node of selectNodes("//Item/node()[starts-with(name(), 'xp-')]", doc)) {
      const property = node as XmlElement;
      let set = "permission_id";
      if (attributeValue(property, "explicit") === "1") set += "|explicit";
      else property.removeAttribute("explicit");
      if (attributeValue(property, "is_null") !== "0") set += "|value";
      else property.removeAttribute("is_null");
      if (!property.hasAttribute("permission_id")) property.setAttribute("permission_id", "");
      insertAttributeFirst(property, "set", set);
    }
  }

  /**
   * Step 7, for a versionable type: the item and its relationships are written under the config id, not the generation's id.
   *
   * @spec EXP-101 EXP-107
   */
  replaceIdWithConfigId(doc: XmlDocument): void {
    const configId = selectSingleNode(`${RESULT_ITEM}/config_id`, doc);
    if (!configId) throw nullReference();
    const text = innerText(configId);
    const item = asElement(selectSingleNode(RESULT_ITEM, doc));
    if (!item) throw nullReference();
    item.setAttribute("id", text);
    for (const sourceId of selectNodes("Relationships/Item/source_id", item)) setInnerText(sourceId as XmlElement, text);
    for (const relationship of selectNodes("Relationships/Item", item)) (relationship as XmlElement).removeAttribute("id");
  }

  /**
   * Step 8 for a RelationshipType: the ItemType it relates is fetched and embedded in `relationship_id`, and the item gets the
   * `dependencyLevel` of the chain of RelationshipTypes above its source.
   *
   * @spec EXP-049 EXP-108 EXP-109
   */
  async processRelationshipType(doc: XmlDocument): Promise<void> {
    const relationshipId = asElement(selectSingleNode(`${RESULT_ITEM}/relationship_id`, doc));
    if (!relationshipId) throw nullReference();
    const id = innerText(relationshipId);
    setInnerText(relationshipId, "");
    const itemType = selectSingleNode(RESULT_ITEM, responseDom(await this.requests.fetchRelationshipItemType(id)));
    if (!itemType) return;
    appendChild(relationshipId, importNode(doc, itemType));
    const sourceId = selectSingleNode(`${RESULT_ITEM}/source_id`, doc);
    if (!sourceId) return;
    const level = await this.helper.lookups.getDepencyLevel(innerText(sourceId), 0);
    asElement(selectSingleNode(RESULT_ITEM, doc))?.setAttribute("dependencyLevel", String(level));
  }

  /**
   * Step 8 for a Sequence: the first `current_value` of the first Sequence item is removed.
   *
   * @spec EXP-110
   */
  processSequence(doc: XmlDocument): void {
    const sequence = selectSingleNode("//Item[@type='Sequence']", doc);
    if (!sequence) return;
    const currentValue = selectSingleNode("current_value", sequence);
    if (currentValue) removeChild(sequence, currentValue);
  }

  /**
   * Step 8 for a Form: the `propertytype_id` of every Field is replaced by the Property it names. The catch around the fetch
   * handles the wrong fault (EXP-112): a Property that is not found aborts the form, any other failure leaves the plain id.
   *
   * @spec EXP-050 EXP-111 EXP-112
   */
  async processForm(doc: XmlDocument): Promise<void> {
    for (const node of selectNodes("//Item[@type='Field']/propertytype_id", doc)) {
      const propertyTypeId = node as XmlElement;
      const nameNode = propertyTypeId.parentNode ? selectSingleNode("name", propertyTypeId.parentNode) : null;
      const fieldName = nameNode ? innerText(nameNode) : "";
      const id = innerText(propertyTypeId);
      let response;
      try {
        response = await this.requests.fetchFieldProperty(id);
      } catch (error) {
        if (!(error instanceof CItemException)) throw error;
        if (error.faultcode !== 0) continue;
        let type = "";
        if (propertyTypeId.getAttributeNode("keyed_name")) {
          const typeAttribute = propertyTypeId.getAttributeNode("type");
          if (!typeAttribute) throw nullReference();
          type = typeAttribute.value;
        }
        error.faultdetail = `Unable to get property ${type} for field ${fieldName}`;
        throw error;
      }
      const property = selectSingleNode(RESULT_ITEM, responseDom(response));
      if (!property) continue;
      setInnerText(propertyTypeId, "");
      appendChild(propertyTypeId, importNode(doc, property));
    }
  }

  /**
   * Step 11, for a dr_RelationshipFamily and, by the copy-paste of EXP-118, for an ac_PolicyAccessItemAttribute: each
   * `dr_relationship_id` of the direct relationships is replaced by the dr_Relationship item it names, whose `implementation_query` is re-indented.
   * The 12.0 engine does this for a dr_RelationshipFamily only, and leaves the `implementation_query` as the server sent it.
   *
   * @spec EXP-051 EXP-117 EXP-118 EXP-121
   */
  async includeDrRelationshipAsValue(doc: XmlDocument): Promise<void> {
    for (const node of selectNodes(`${RESULT_ITEM}/Relationships/Item/dr_relationship_id`, doc)) {
      const drRelationshipId = node as XmlElement;
      const id = innerText(drRelationshipId);
      setInnerText(drRelationshipId, "");
      const drRelationship = selectSingleNode(RESULT_ITEM, responseDom(await this.requests.fetchDrRelationship(id)));
      if (!drRelationship) continue;
      const query = this.helper.engine === "12.0" ? null : selectSingleNode("//implementation_query", drRelationship);
      if (query) setInnerText(query as XmlElement, xdocumentToString(innerText(query)));
      appendChild(drRelationshipId, importNode(doc, drRelationship));
    }
  }

  /**
   * Step 12, for a dac_DomainDefinition: the `condition_xml` of every dac_SubdomainPermission holds its XML re-indented, as
   * text.
   *
   * @spec EXP-119 EXP-120
   */
  indentConditionXmlInDAC(doc: XmlDocument): void {
    for (const node of selectNodes("//Item[@type='dac_SubdomainPermission']/condition_xml", doc)) {
      const condition = node as XmlElement;
      setInnerXml(condition, htmlDecode(getInnerXml(condition)));
      const indented = writeNodes(childrenOf(condition), { indentChars: " ", conformance: "fragment" });
      setInnerXml(condition, htmlEncode(indented));
    }
  }
}

/** `Item.getID()` of the item: its `id` attribute, or the trimmed text of its plain `id` property. */
function itemIdOf(item: XmlElement): string {
  const id = attributeValue(item, "id") ?? "";
  if (id !== "") return id;
  const property = selectSingleNode("id[not(@condition) or @condition='eq']", item);
  return property ? trimWhiteSpace(innerText(property)) : "";
}

/** `Item.getRelationships()`: the items in the `Relationships` elements of an item. */
function relationshipsOf(item: AnswerElement): AnswerElement[] {
  return childElements(item, "Relationships").flatMap((relationships) => childElements(relationships, "Item"));
}

/**
 * Removes from the copy the relationship whose `relationship_id` is the generated type of a cmf item. There must be exactly
 * one, or IOM refuses.
 *
 * @spec EXP-104
 */
export function removeRelationshipHelper(cmfItem: AnswerElement, itemType: XmlElement): void {
  const generatedType = getProperty(cmfItem, "generated_type") ?? "";
  const matches = selectNodes(`Relationships/Item[relationship_id='${generatedType}']`, itemType);
  const [match, ...others] = matches;
  if (!match || others.length > 0) throw new DotNetException("System.ArgumentException", NOT_A_SINGLE_ITEM_ARGUMENT);
  if (match.parentNode) removeChild(match.parentNode, match);
}

/**
 * Puts a new attribute in front of all others and takes an old one of the same name out (`Attributes.InsertBefore(attribute,
 * Attributes[0])`).
 */
function insertAttributeFirst(element: XmlElement, name: string, value: string): void {
  const others = attributesOf(element).filter((attribute) => attribute.name !== name);
  for (const attribute of attributesOf(element)) element.removeAttributeNode(attribute);
  element.setAttribute(name, value);
  for (const attribute of others) {
    if (attribute.namespaceURI) element.setAttributeNodeNS(attribute);
    else element.setAttributeNode(attribute);
  }
}

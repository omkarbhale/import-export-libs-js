import { CDATA_SECTION_NODE, ELEMENT_NODE, TEXT_NODE, innerText } from "../xml/index.js";
import type { XmlElement, XmlNode } from "../xml/index.js";
import { attributeOf, childElements, isNamed, parentElement } from "./source.js";
import { SYSTEM_PROPERTIES } from "./system-names.js";

/**
 * The templates of `export.xsl` that write nothing: the system elements and Properties that the server fills in or that an
 * ItemType edit carries instead. Each function says whether a template of that kind matches a node; the transform then skips it.
 *
 * @spec EXP-310 EXP-311 EXP-312 EXP-313 EXP-314 EXP-315 EXP-316
 */

/** The elements dropped wherever they sit, whatever their parent (EXP-311). */
const SYSTEM_ELEMENTS: ReadonlySet<string> = new Set([
  "cache_query",
  "config_id",
  "core",
  "created_by_id",
  "created_on",
  "current_state",
  "generation",
  "history_id",
  "id",
  "is_cached",
  "is_current",
  "is_released",
  "keyed_name",
  "locked_by_id",
  "major_rev",
  "minor_rev",
  "modified_by_id",
  "modified_on",
  "new_version",
  "not_lockable",
  "state",
  "itemtype",
  "release_date",
  "effective_date",
  "superseded_date",
]);

/** The three system dates, which are dropped only from a versionable ItemType (EXP-310). */
const DATED_PROPERTIES: readonly string[] = ["effective_date", "release_date", "superseded_date"];

/** The Property names dropped from every ItemType definition (EXP-310): the 32 system names but for the three dates. */
const DROPPED_PROPERTY_NAMES: ReadonlySet<string> = new Set(
  SYSTEM_PROPERTIES.split("|").filter((name) => name !== "" && !DATED_PROPERTIES.includes(name)),
);

/** `Item[@type='T']`'s `@type`, when the element is an `Item` that has one. */
function itemType(element: XmlElement | null): string | undefined {
  return element && isNamed(element, "Item") ? attributeOf(element, "type") : undefined;
}

/** `child='value'`: some child element of that name has exactly this string-value. */
function hasChildEqual(element: XmlElement, name: string, value: string): boolean {
  return childElements(element, name).some((child) => innerText(child) === value);
}

/**
 * An `Item` of type `Property` that writes nothing: a keyed one, one named for a system column, and a dated one of a versionable
 * ItemType (the Item two levels up).
 *
 * @spec EXP-310
 */
export function isDroppedProperty(item: XmlElement): boolean {
  if (attributeOf(item, "type") !== "Property") return false;
  if (hasChildEqual(item, "is_keyed", "1")) return true;
  const names = childElements(item, "name").map((name) => innerText(name));
  if (names.some((name) => DROPPED_PROPERTY_NAMES.has(name))) return true;
  if (!names.some((name) => DATED_PROPERTIES.includes(name))) return false;
  const owner = parentElement(item)?.parentNode ?? null;
  return owner?.nodeType === ELEMENT_NODE && hasChildEqual(owner as XmlElement, "is_versionable", "1");
}

/**
 * An element, not an `Item`, that writes nothing: the system elements, the conditional ones, the autogenerated columns, the
 * Variable and User trimming and an empty `Relationships`.
 *
 * @spec EXP-311 EXP-312 EXP-313 EXP-314 EXP-315 EXP-316
 */
export function isDroppedElement(element: XmlElement): boolean {
  if (element.namespaceURI) return false;
  const name = element.localName ?? "";
  if (SYSTEM_ELEMENTS.has(name)) return true;
  const parent = parentElement(element);
  const parentType = itemType(parent);
  switch (name) {
    case "behavior":
      // `Item[@type!='RelationshipType']`: the Item must have a type, and a different one
      return parentType !== undefined && parentType !== "RelationshipType";
    case "css":
      return parentType !== undefined && parentType !== "Field" && parentType !== "Body";
    case "item_behavior":
      return parentType === "Property" && parent !== null && childElements(parent, "data_type").some((e) => innerText(e) !== "item");
    case "generated_type":
      return parentType === "cmf_ElementType" || parentType === "cmf_PropertyType";
    case "execution_count":
      return parentType === "SQL";
    case "pwd_is_set_on":
      return parentType === "User";
    case "value":
      return parentType === "Variable" && parent !== null && isDroppedVariableValue(element, parent);
    case "default_value":
      return parentType === "Variable" && innerText(element) === "";
    case "Relationships":
      return !hasElementChild(element);
    default:
      return false;
  }
}

function hasElementChild(element: XmlElement): boolean {
  for (let child = element.firstChild; child; child = child.nextSibling) {
    if (child.nodeType === ELEMENT_NODE) return true;
  }
  return false;
}

/**
 * The text nodes of an element as XPath sees them: each maximal run of adjacent text and CDATA nodes is one. A comment, a
 * processing instruction or an element ends a run.
 */
function textNodes(element: XmlNode): string[] {
  const runs: string[] = [];
  let open = false;
  for (let child = element.firstChild; child; child = child.nextSibling) {
    if (child.nodeType === TEXT_NODE || child.nodeType === CDATA_SECTION_NODE) {
      const data = (child as unknown as { data: string }).data;
      if (open) runs[runs.length - 1] += data;
      else runs.push(data);
      open = true;
    } else {
      open = false;
    }
  }
  return runs;
}

/**
 * `value[text()=../default_value/text() or string-length()=0]`: empty, or one of its text nodes equals a text node of one of the
 * Variable's `default_value` children.
 */
function isDroppedVariableValue(value: XmlElement, variable: XmlElement): boolean {
  if (innerText(value) === "") return true;
  const defaults = childElements(variable, "default_value").flatMap((e) => textNodes(e));
  return textNodes(value).some((text) => defaults.includes(text));
}

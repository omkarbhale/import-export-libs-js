import { describe, expect, it } from "vitest";
import { CItemException } from "../client/fault.js";
import { CItemHelper } from "../client/item-helper.js";
import { loadProbe } from "../client/probe-fixture.js";
import { StubConnection, StubStop, stubFault, stubResult } from "../client/stub-connection.js";
import { ArasVersion } from "../client/version.js";
import { CExportItems } from "./cexport-items.js";
import { ExportItem } from "./export-item.js";

const probe = loadProbe("14.0.7");

/** `Run-Seq` of the probe: the answers in order, then a stop; what the port sends is the follow-up requests it builds. */
function over(answers: string[]) {
  let next = 0;
  const stub = new StubConnection(() => answers[next++]);
  const helper = new CItemHelper(stub);
  helper.innovatorVersion = new ArasVersion(14, 0, 9, 1, 0);
  return { stub, helper, exporter: new CExportItems(helper) };
}

const notVersionable = stubResult('<Item type="ItemType" id="X"><is_versionable>0</is_versionable></Item>');
const noFloat = stubFault("0", "No items of type ItemType found.");

/** Runs `steps` until the script runs out of answers. */
async function untilStopped(steps: () => Promise<unknown>): Promise<void> {
  try {
    await steps();
  } catch (error) {
    if (!(error instanceof StubStop)) throw error;
  }
}

describe("the requests that follow the main fetch, replayed from the probe's N scenarios (EXP-048 to EXP-051)", () => {
  it("N.itemType: the auto-generated relationship query is sent as ApplyAML", async () => {
    const { stub, exporter } = over([notVersionable, stubResult('<Item type="ItemType" id="ID1"><name>Part</name></Item>')]);
    await untilStopped(async () => {
      await exporter.fetch(new ExportItem("k", "ID1", "ItemType"), "");
      await exporter.queryAutoGeneratedRelationships("ID1");
    });
    expect(stub.requests).toEqual(probe["N.itemType"].requests);
    expect(stub.actions).toEqual(probe["N.itemType"].actions);
  });

  it("N.relationshipType: the ItemType fetch by id, then the dependency chain", async () => {
    const { stub, helper, exporter } = over([
      notVersionable,
      stubResult('<Item type="RelationshipType" id="ID1"><relationship_id keyed_name="X" type="ItemType">REL1</relationship_id><source_id keyed_name="S" type="ItemType">SRC1</source_id></Item>'),
      stubResult('<Item type="ItemType" id="REL1"><name>X</name></Item>'),
      stubResult('<Item type="RelationshipType" id="R9"><source_id>SRC2</source_id></Item>'),
    ]);
    await untilStopped(async () => {
      await exporter.fetch(new ExportItem("k", "ID1", "RelationshipType"), "");
      await exporter.fetchRelationshipItemType("REL1");
      await helper.lookups.getDepencyLevel("SRC1", 0);
    });
    expect(stub.requests).toEqual(probe["N.relationshipType"].requests);
    expect(stub.actions).toEqual(probe["N.relationshipType"].actions);
  });

  it("N.form: the Property fetch of a Field", async () => {
    const { stub, exporter } = over([
      notVersionable,
      stubResult('<Item type="Form" id="ID1"><Relationships><Item type="Field" id="F1"><name>fld</name><propertytype_id keyed_name="p" type="Property">PT1</propertytype_id></Item></Relationships></Item>'),
    ]);
    await untilStopped(async () => {
      await exporter.fetch(new ExportItem("k", "ID1", "Form"), "");
      await exporter.fetchFieldProperty("PT1");
    });
    expect(stub.requests).toEqual(probe["N.form"].requests);
  });

  it.each(["N.drRelationshipFamily", "N.acPolicyAccessItemAttribute"])("%s: the dr_Relationship fetch", async (scenario) => {
    const type = probe[scenario].type as string;
    const drRelationship = stubResult('<Item type="dr_Relationship" id="DRID1"><implementation_query>&lt;a&gt;&lt;b/&gt;&lt;/a&gt;</implementation_query></Item>');
    const { stub, helper, exporter } = over([
      notVersionable,
      stubResult(`<Item type="${type}" id="ID1"><Relationships><Item type="X" id="Q"><dr_relationship_id>DRID1</dr_relationship_id></Item></Relationships></Item>`),
      noFloat,
      noFloat,
      drRelationship,
    ]);
    await untilStopped(async () => {
      await exporter.fetch(new ExportItem("k", "ID1", type), "");
      await helper.lookups.getCustomFloatPropertiesOfTypeItem(type);
      await helper.lookups.getCustomFloatPropertiesOfTypeItem(`${type}_Relationship`.replace("ac_PolicyAccessItemAttribute_Relationship", "dr_RelationshipFamily_Relationship"));
      await exporter.fetchDrRelationship("DRID1");
      await helper.lookups.getPolytypeNames();
    });
    expect(stub.requests.slice(0, 2).concat(stub.requests.slice(4))).toEqual(probe[scenario].requests.slice(0, 2).concat(probe[scenario].requests.slice(4)));
    expect(stub.requests[2]).toContain(`<name>${type}</name>`);
  });

  it("N.versionablePart: the current-id lookup, the main fetch, then the float properties", async () => {
    const { stub, helper, exporter } = over([
      stubResult('<Item type="ItemType" id="X"><is_versionable>1</is_versionable></Item>'),
      stubResult('<Item type="X" id="ID1"><config_id>CFG1</config_id><is_current>1</is_current></Item>'),
      stubResult('<Item type="Part" id="ID1"><config_id>CFG1</config_id></Item>'),
      noFloat,
    ]);
    await exporter.fetch(new ExportItem("k", "ID1", "Part"), "");
    await helper.lookups.getCustomFloatPropertiesOfTypeItem("Part");
    expect(stub.requests).toEqual(probe["N.versionablePart"].requests);
  });
});

describe("the first three requests of an item (EXP-001)", () => {
  it("returns the file name, the id the main fetch asked for, and the answer", async () => {
    const { exporter } = over([
      stubResult('<Item type="ItemType" id="X"><is_versionable>1</is_versionable></Item>'),
      stubResult('<Item type="Part" id="OLD"><config_id>CFG</config_id><is_current>0</is_current></Item>'),
      stubResult('<Item type="Part" id="NEW"><id>NEW</id></Item>'),
      stubResult('<Item type="Part" id="NEW"><name>the part</name></Item>'),
    ]);
    const fetched = await exporter.fetch(new ExportItem("the/part", "OLD", "Part"), "2");
    expect(fetched).toMatchObject({ fileName: "OLD.xml", versionable: true, id: "NEW" });
    expect(fetched.request).toBe(
      '<Item type="Part" action="get" levels="2" select="xp-*($value, @explicit, @permission_id), *[is_not_null()]"><id>NEW</id></Item>',
    );
    expect(fetched.response.outerXml).toContain("<name>the part</name>");
  });

  it("sends nothing after the lookup of a type the server does not know", async () => {
    const { stub, exporter } = over([stubFault("0", "No items of type ItemType found.")]);
    await expect(exporter.fetch(new ExportItem("k", "ID", "Nope"), "")).rejects.toMatchObject({
      faultcode: 0,
      faultdetail: "Unable to get definition of System.Xml.XmlAttribute: Nope",
    });
    expect(stub.requests).toHaveLength(1);
  });

  it("does not catch a fault of the main fetch, faultcode 0 included (O.mainFetchFault)", async () => {
    for (const code of ["0", "999"]) {
      const { exporter } = over([notVersionable, stubFault(code, "No items of type Part found.")]);
      const failure = await exporter.fetch(new ExportItem("k", "ID1", "Part"), "").catch((error: unknown) => error);
      expect(failure).toBeInstanceOf(CItemException);
      expect((failure as CItemException).faultcode).toBe(Number(code));
      expect((failure as CItemException).message).toContain('Request: <Item type="Part" action="get" levels="1"');
    }
  });

  it("needs a logged-in helper for the default row (NullReferenceException, wrapped by EXP-054)", async () => {
    const { helper, exporter } = over([notVersionable]);
    helper.innovatorVersion = undefined;
    await expect(exporter.fetch(new ExportItem("k", "ID", "Part"), "")).rejects.toMatchObject({
      faultcode: -1,
      message: "Object reference not set to an instance of an object. Can't export item.",
    });
  });
});

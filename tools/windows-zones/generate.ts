/**
 * Generates src/client/windows-zones.ts from two CLDR files: the Windows zone
 * mapping (common/supplemental/windowsZones.xml) and the time zone aliases
 * (common/bcp47/timezone.xml). Every IANA id, canonical or alias, maps to a
 * Windows time zone id the way WIRE-005 describes: the id is first resolved to
 * CLDR's canonical one (the first alias of its `type`), then looked up in the
 * `mapZone` whose type list holds it, preferring territory 001.
 *
 * Usage: tsx tools/windows-zones/generate.ts [cldr-release-tag]   (default release-47)
 */
import { writeFileSync } from "node:fs";

const release = process.argv[2] ?? "release-47";
const base = `https://raw.githubusercontent.com/unicode-org/cldr/${release}/common`;

async function fetchText(path: string): Promise<string> {
  const response = await fetch(`${base}/${path}`);
  if (!response.ok) throw new Error(`${path}: ${response.status} ${response.statusText}`);
  return response.text();
}

const windowsZones = await fetchText("supplemental/windowsZones.xml");
const timezones = await fetchText("bcp47/timezone.xml");

// IANA id -> its CLDR canonical id.
const canonical = new Map<string, string>();
for (const match of timezones.matchAll(/<type\b[^>]*\balias="([^"]+)"/g)) {
  const aliases = (match[1] ?? "").split(/\s+/).filter(Boolean);
  for (const alias of aliases) canonical.set(alias, aliases[0] ?? alias);
}

// CLDR canonical id -> Windows id; territory 001 wins over the others.
const windowsId = new Map<string, { id: string; global: boolean }>();
for (const match of windowsZones.matchAll(/<mapZone\b[^>]*\bother="([^"]+)"[^>]*\bterritory="([^"]+)"[^>]*\btype="([^"]+)"/g)) {
  const [, other = "", territory = "", types = ""] = match;
  for (const type of types.split(/\s+/).filter(Boolean)) {
    const known = windowsId.get(type);
    if (!known || (territory === "001" && !known.global)) windowsId.set(type, { id: other, global: territory === "001" });
  }
}

const table = new Map<string, string>();
for (const id of new Set([...canonical.keys(), ...windowsId.keys()])) {
  const windows = windowsId.get(canonical.get(id) ?? id) ?? windowsId.get(id);
  if (windows) table.set(id, windows.id);
}

const rows = [...table].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)).map(([iana, windows]) => `  ${JSON.stringify(iana)}: ${JSON.stringify(windows)},`);
const out = `// Generated by tools/windows-zones/generate.ts from Unicode CLDR ${release}
// (common/supplemental/windowsZones.xml and common/bcp47/timezone.xml). Do not edit.
// Copyright © 1991-Present Unicode, Inc. Distributed under the Unicode License v3 (https://www.unicode.org/license.txt).

/** IANA time zone id (canonical or alias) to the Windows time zone id CLDR maps it to. */
export const WINDOWS_ZONE_IDS: Readonly<Record<string, string>> = {
${rows.join("\n")}
};
`;
writeFileSync(new URL("../../src/client/windows-zones.ts", import.meta.url), out);
console.log(`wrote ${table.size} zones from ${release}`);

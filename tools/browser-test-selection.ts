/**
 * Which of the library's unit test files run unedited in the browsers (HOST-264): the ones whose import closure, under the
 * browser's module graph, reaches no Node API. The selection is written to `src/browser/pure-tests.json`, which the `browser`
 * project of `vitest.config.ts` includes next to the `*.browser.test.ts` files, and a test of the Node project fails when the
 * file is stale.
 *
 * A test file is *pure* when, in its closure (the test, and every file it imports at run time, with `src/host/default-host.ts`
 * replaced by `default-host.browser.ts` as in the bundle and in the browser project):
 *
 * - no module is a Node built-in, with or without the `node:` prefix, and no string literal names one (`vi.mock("node:fs")`);
 * - no file lies outside `src/` (`oracle/`, `tools/`, `spec/`, `fixtures/` are Node-side files and data);
 * - no file uses a global that only Node has (`process`, `__dirname`, `__filename`, `require`, `setImmediate`, `global`, `module`,
 *   `exports`) or reads the location of the module with `import.meta.url`, `import.meta.dirname` or `import.meta.filename`.
 *
 * A test that reads a recorded fixture does so through `node:fs` and is therefore not pure; the replays of the fixtures are
 * the browser tests of tickets 24 and 25. The closure is computed, not listed, so that a test that becomes pure or impure is
 * noticed.
 *
 * Test-only tooling: nothing under `src/` imports it.
 *
 *   npx tsx tools/browser-test-selection.ts            print the selection and what is left out, and why
 *   npx tsx tools/browser-test-selection.ts --write    write src/browser/pure-tests.json
 */
import { build } from "esbuild";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { builtinModules } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { repoRoot, replaceDefaultHost } from "./browser-bundle.js";

/** The checked-in selection, relative to the repository root. */
export const SELECTION_FILE = "src/browser/pure-tests.json";

/** Where the test files that may be selected are. The tests of `spec/`, `tools/` and `oracle/` are Node-side by their place. */
const TEST_ROOT = "src";

/** The test files the browser project already runs under its own name; they are not part of the selection. */
const BROWSER_TEST = /\.browser\.test\.ts$/;

const BUILTINS = new Set(builtinModules.flatMap((name) => [name, `node:${name}`]));

/** Globals that a browser page lacks and Node has. `Buffer` is not here: the page gets the `buffer` package (HOST-262). */
const NODE_GLOBALS = new Set(["process", "__dirname", "__filename", "require", "setImmediate", "clearImmediate", "global", "module", "exports"]);

/** `import.meta` members that locate a module on a disk. */
const NODE_META = new Set(["url", "dirname", "filename"]);

/** The shape of the checked-in file. */
export interface PureTestsFile {
  /** What the file is and how it is made, for a reader of the JSON. */
  note: string;
  /** Test files, repository-relative POSIX paths, sorted by code unit. */
  files: string[];
}

export interface Selection {
  /** The test files that run in the browsers, sorted. */
  pure: string[];
  /** The other test files with the first reason each is left out, sorted by path. */
  impure: Record<string, string>;
}

const NOTE =
  "Generated by tools/browser-test-selection.ts (npx tsx tools/browser-test-selection.ts --write). The unit tests whose import closure reaches no Node API; the browser project runs them unedited (HOST-264).";

function toPosix(file: string): string {
  return file.split(path.sep).join("/");
}

function listTests(root: string): string[] {
  const found: string[] = [];
  const walk = (folder: string): void => {
    for (const entry of readdirSync(path.join(root, folder), { withFileTypes: true })) {
      const relative = `${folder}/${entry.name}`;
      if (entry.isDirectory()) walk(relative);
      else if (entry.isFile() && entry.name.endsWith(".test.ts") && !BROWSER_TEST.test(entry.name)) found.push(relative);
    }
  };
  walk(TEST_ROOT);
  return found.sort();
}

/** Why one source file by itself needs Node: a built-in named in a literal, a Node-only global or a module location. */
export function ownReason(text: string, fileName = "file.ts"): string | undefined {
  const source = ts.createSourceFile(fileName, text, ts.ScriptTarget.ES2022, true);
  const declared = declaredNames(source);
  let reason: string | undefined;
  const visit = (node: ts.Node): void => {
    if (reason !== undefined) return;
    if (ts.isStringLiteralLike(node) && BUILTINS.has(node.text) && node.text.startsWith("node:")) {
      reason = `names ${node.text}`;
    } else if (ts.isIdentifier(node) && NODE_GLOBALS.has(node.text) && !declared.has(node.text) && isFreeReference(node)) {
      reason = `uses ${node.text}`;
    } else if (
      ts.isMetaProperty(node) &&
      node.keywordToken === ts.SyntaxKind.ImportKeyword &&
      ts.isPropertyAccessExpression(node.parent) &&
      NODE_META.has(node.parent.name.text)
    ) {
      reason = `uses import.meta.${node.parent.name.text}`;
    }
    if (reason === undefined) ts.forEachChild(node, visit);
  };
  visit(source);
  return reason;
}

/** The names that the file binds itself (a variable, a parameter, a function, an import), wherever in the file; a coarse scope. */
function declaredNames(source: ts.SourceFile): Set<string> {
  const names = new Set<string>();
  const visit = (node: ts.Node): void => {
    if (
      (ts.isVariableDeclaration(node) || ts.isParameter(node) || ts.isFunctionDeclaration(node) || ts.isBindingElement(node) || ts.isClassDeclaration(node) || ts.isImportSpecifier(node) || ts.isNamespaceImport(node) || ts.isImportClause(node)) &&
      node.name !== undefined &&
      ts.isIdentifier(node.name)
    ) {
      names.add(node.name.text);
    }
    ts.forEachChild(node, visit);
  };
  visit(source);
  return names;
}

/** An identifier that reads a global: not a member name, a key, a label, a type position or a declaration of the same name. */
function isFreeReference(node: ts.Identifier): boolean {
  const parent = node.parent;
  if (ts.isPropertyAccessExpression(parent) && parent.name === node) return false;
  if (ts.isQualifiedName(parent) && parent.right === node) return false;
  if ((ts.isPropertyAssignment(parent) || ts.isPropertySignature(parent) || ts.isMethodDeclaration(parent) || ts.isPropertyDeclaration(parent)) && parent.name === node) return false;
  if (ts.isShorthandPropertyAssignment(parent) && parent.name === node) return true;
  if (ts.isTypeReferenceNode(parent) || ts.isExpressionWithTypeArguments(parent) || ts.isTypeQueryNode(parent)) return false;
  if (ts.isImportSpecifier(parent) || ts.isExportSpecifier(parent) || ts.isNamespaceImport(parent) || ts.isImportClause(parent)) return false;
  if ((ts.isVariableDeclaration(parent) || ts.isParameter(parent) || ts.isFunctionDeclaration(parent) || ts.isBindingElement(parent)) && parent.name === node) return false;
  return true;
}

/**
 * The selection of the test files under `root`. Every test is an esbuild entry of one build, and the metafile's graph of
 * imports gives each its closure; bare package imports are not followed (`@xmldom/xmldom`, `xpath`, `buffer` and `vitest` run in
 * a page), a Node built-in is a reason.
 */
export async function selectPureTests(root: string = repoRoot): Promise<Selection> {
  const tests = listTests(root);
  const result = await build({
    absWorkingDir: root,
    entryPoints: tests.map((test) => path.join(root, test)),
    bundle: true,
    write: false,
    metafile: true,
    outdir: path.join(root, ".selection-out"),
    format: "esm",
    platform: "node",
    target: "es2022",
    packages: "external",
    plugins: [replaceDefaultHost(root)],
    tsconfig: path.join(root, "tsconfig.json"),
    logLevel: "silent",
  });
  const inputs = result.metafile.inputs;
  const ownCache = new Map<string, string | undefined>();
  const own = (file: string): string | undefined => {
    if (!ownCache.has(file)) ownCache.set(file, ownReason(readFileSync(path.join(root, file), "utf8"), file));
    return ownCache.get(file);
  };

  const closureReason = (test: string): string | undefined => {
    const seen = new Set<string>();
    const stack = [test];
    while (stack.length > 0) {
      const file = stack.pop() as string;
      if (seen.has(file)) continue;
      seen.add(file);
      if (!file.startsWith(`${TEST_ROOT}/`)) return `${file} is outside ${TEST_ROOT}/`;
      const found = own(file);
      if (found !== undefined) return `${file} ${found}`;
      for (const imported of inputs[file]?.imports ?? []) {
        if (imported.external) {
          if (BUILTINS.has(imported.path)) return `${file} imports ${imported.path}`;
          continue;
        }
        stack.push(imported.path);
      }
    }
    return undefined;
  };

  const pure: string[] = [];
  const impure: Record<string, string> = {};
  for (const test of tests) {
    const reason = closureReason(test);
    if (reason === undefined) pure.push(test);
    else impure[test] = reason;
  }
  return { pure, impure };
}

export function toFile(selection: Selection): PureTestsFile {
  return { note: NOTE, files: selection.pure };
}

export function readSelectionFile(root: string = repoRoot): PureTestsFile {
  return JSON.parse(readFileSync(path.join(root, SELECTION_FILE), "utf8")) as PureTestsFile;
}

export function renderSelectionFile(file: PureTestsFile): string {
  return `${JSON.stringify(file, null, 2)}\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const selection = await selectPureTests();
  if (process.argv.includes("--write")) {
    writeFileSync(path.join(repoRoot, SELECTION_FILE), renderSelectionFile(toFile(selection)));
    console.log(`wrote ${SELECTION_FILE}: ${selection.pure.length} pure test files, ${Object.keys(selection.impure).length} left out`);
  } else {
    console.log(`${selection.pure.length} pure test files; ${Object.keys(selection.impure).length} left out:`);
    for (const [file, reason] of Object.entries(selection.impure)) console.log(`  ${toPosix(file)}  ${reason}`);
  }
}
